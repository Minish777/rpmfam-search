def _words(text: str) -> set[str]:
    """Слова текста в нижнем регистре без «ё», с дефисом как разделителем.

    NFKD здесь применять нельзя: он разбирает «й» на «и» плюс диакритика,
    и «белый» превращался в «бело», из-за чего цвета не ловились.
    """
    out = set()
    for chunk in re.split(r"[\s\-–—]+", text.lower().replace("ё", "е")):
        chunk = re.sub(r"[^a-zа-я0-9]", "", chunk)
        if chunk:
            out.add(chunk)
    return out


def _load(block: str) -> set[str]:
    return {w for w in block.split() if w}


