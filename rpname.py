def clean_name(raw: str) -> str:
    """Убирает ник в скобках, теги и лишние пробелы."""
    s = raw.strip()
    s = re.sub(r"[\[(<].*?[\])>]", " ", s)
    s = re.sub(r"[#@]", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def _stem_hit(word: str, stems: set[str]) -> str | None:
    """Ищет стем в начале слова или как его корень: сука -> сук..."""
    for stem in stems:
        if word == stem:
            return stem
        if word.startswith(stem):
            return stem
        core = word[:-1] if len(word) > 4 else ""
        if core and (core == stem or core.startswith(stem)):
            return stem
    return None


# Допустимые окончания после корня. Нужны, чтобы ловить «Дураков» и
# «Модераторов», но не рубить настоящие фамилии: «Котлов» — фамилия,
# «Кот» — рофло, и отличаются они окончанием.
_SUFFIXES = {
    "", "а", "у", "е", "ы", "и", "я", "й", "о", "ов", "ев", "ин", "ын",
    "ам", "ах", "ям", "ях", "ой", "ей", "ую", "ая", "ое", "ые", "ых",
    "его", "ому", "ани", "яни", "ат", "ят", "ух", "их", "им",
}


def _root_hit(word: str, stems: set[str]) -> str | None:
    """Слово начинается с корня и остаток — нормальное русское окончание."""
    for stem in stems:
        if word == stem or word.startswith(stem):
            rest = word[len(stem):]
            if rest in _SUFFIXES:
                return stem
    return None


def check_name(raw: str) -> list[Finding]:
    """Полная проверка РП имени. Возвращает список находок."""
    name = clean_name(raw)
    out: list[Finding] = []

    if not name:
        return [Finding(BLOCK, "Пустое имя",
                        "введите имя и фамилию, например: Алекс Вендетто")]

    parts = [p for p in re.split(r"\s+", name) if p]
    first = parts[0] if parts else ""
    surnames = parts[1:]
    words = _words(name)
    # склейка всех частей без разделителей: «Цун Дере» -> «цундере»
    glued = "".join(re.findall(r"[a-zа-я]+",
                               name.lower().replace("ё", "е")))

    # --- формат -----------------------------------------------------
    bad = sorted({ch for ch in name if ch not in ALLOWED_CHARS})
    if bad:
        out.append(Finding(
            BLOCK, "Лишние символы в имени",
            "недопустимые символы: " + ", ".join(repr(c) for c in bad),
            RULES["cyr"]))
    else:
        out.append(Finding(OK, "Только русский язык, лишних символов нет",
                           rule=RULES["cyr"]))

    if "_" in name:
        out.append(Finding(BLOCK, "Нижнее подчёркивание",
                           f"в имени есть «_»: {name}", RULES["underscore"]))
    else:
        out.append(Finding(OK, "Без нижних подчёркиваний",
                           rule=RULES["underscore"]))

    wrong_caps = []
    shouty = []
    for p in parts:
        for piece in [x for x in re.split(r"[\-–—]", p) if x]:
            if piece[:1].islower():
                wrong_caps.append(piece)
            elif piece.isupper() and len(piece) > 1:
                shouty.append(piece)
    if wrong_caps:
        out.append(Finding(
            BLOCK, "Регистр букв",
            "с большой буквы начинаются только имя и каждая часть фамилии: "
            + ", ".join(wrong_caps),
            RULES["caps"]))
    elif shouty:
        # правило требует заглавной в начале слова, а не запрещает её внутри.
        # «МакКонелл» — фамилия с большой буквы посередине, это нормально.
        out.append(Finding(
            WARN, "Имя или фамилия целиком капсом",
            "так не принято: " + ", ".join(shouty),
            RULES["caps"]))
    else:
        out.append(Finding(OK, "С заглавных букв, как положено",
                           rule=RULES["caps"]))

    # фамилия может быть двойной: считаем куски через дефис
    surname_pieces = []
    for part in surnames:
        surname_pieces.extend(x for x in re.split(r"[\-–—]", part) if x)

    if len(parts) < 2:
        out.append(Finding(BLOCK, "Нет фамилии",
                           "нужно имя и фамилия, например: Алекс Вендетто"))
    elif len(surname_pieces) > 2:
        out.append(Finding(BLOCK, "Тройная фамилия",
                           "частей фамилии больше двух: " + " ".join(surname_pieces),
                           RULES["triple"]))
    elif len(surname_pieces) == 2:
        out.append(Finding(OK, "Двойная фамилия, не тройная", rule=RULES["triple"]))
    else:
        out.append(Finding(OK, "Одна фамилия, не тройная", rule=RULES["triple"]))

    # --- полная форма имени -----------------------------------------
    short = SHORT_NAMES.get(key_of(first)) or SHORT_NAMES.get(first.lower())
    if short:
        out.append(Finding(
            BLOCK, "Имя не в полной форме",
            f"«{first}» — сокращение, полная форма: {short}",
            RULES["short"], fix=short.split(" или ")[0]))
    else:
        out.append(Finding(OK, "Имя в полной форме", rule=RULES["short"]))

    # --- прямые запреты ------------------------------------------------
    prof = _stem_hit_in(words, PROFANITY_S)
    if prof:
        out.append(Finding(BLOCK, "Мат",
                           f"похоже на «{prof}»", RULES["profanity"]))
    else:
        out.append(Finding(OK, "Мата нет", rule=RULES["profanity"]))

    svc = sorted({h for w in words if (h := _root_hit(w, SERVICE_S))})
    if svc:
        out.append(Finding(BLOCK, "Служебное слово в имени",
                           ", ".join(svc), RULES["service"]))
    else:
        out.append(Finding(OK, "Служебных слов нет", rule=RULES["service"]))

    # --- запрещённые фамилии ------------------------------------------
    for label, stems, rule in (
        ("Цвет", COLORS_S, RULES["color"]),
        ("Профессия или должность", PROFESSIONS_S, RULES["profession"]),
        ("Язык", LANGUAGES_S, RULES["language"]),
        ("Страна, город или регион", PLACES_S, RULES["place"]),
        ("Животное", ANIMALS_S, RULES["animal"]),
        ("Предмет или еда", STUFF_S, RULES["animal"]),
        ("Рофлофамилия", ROFLOP_S, RULES["roflop"]),
    ):
        hit = sorted({h for w in words if (h := _root_hit(w, stems))})
        if hit:
            out.append(Finding(BLOCK, f"{label} вместо фамилии",
                               ", ".join(hit), rule))
    if not any(f.level == BLOCK and f.title.startswith(
            ("Цвет", "Профессия", "Язык", "Страна", "Животное", "Предмет",
             "Рофло")) for f in out):
        out.append(Finding(OK, "Запрещённых слов-фамилий нет",
                           rule="цвета, профессии, языки, страны, "
                                "животные, предметы"))

    # --- завуалированные и известные ------------------------------------
    arch = _contains(glued, ARCHETYPE_S) or _archetype_by_tail(surnames)
    if arch:
        out.append(Finding(
            BLOCK, "Завуалированный аниме-архетип",
            f"склеенные части дают «{arch}» — правило прямо запрещает такие "
            f"имена", RULES["disguised"]))
    else:
        out.append(Finding(OK, "Завуалированных слов нет", rule=RULES["disguised"]))

    fam = _contains(glued, FAMOUS_S)
    if fam:
        out.append(Finding(BLOCK, "Похоже на известную личность",
                           f"склеенные части дают «{fam}»", RULES["famous"]))
    else:
        out.append(Finding(OK, "Известных личностей не найдено",
                           rule=RULES["famous"]))

    return out


# Хвосты, из которых склеиваются архетипы: «Цун Дере», «Куд Ере», «Ян Ере».
# Правило запрещает их явно, а общего корня у всех нет — «цудере» не
# содержит «цундер», «янере» не содержит «яндер».
ARCHETYPE_TAILS = {"дере", "дере", "дер", "дерэ", "ере", "эре", "дери"}


def _archetype_by_tail(surnames) -> str | None:
    for s in surnames:
        for piece in re.split(r"[\-–—]", s):
            if key_of(piece) in ARCHETYPE_TAILS:
                return key_of(piece)
    return None


def _contains(glued: str, stems: set[str]) -> str | None:
    """Ищет стем где угодно внутри склейки, а не только в начале.

    «Адо Альгит-Лер» склеивается в «адоальгитлер», и «алгитлер» сидит
    в середине — с проверкой начала такое не находилось.

    Короткие стемы пропускаем: «чен» находился внутри «Музыченко».
    """
    for stem in stems:
        if stem and len(stem) >= 5 and stem in glued:
            return stem
    return None


def _stem_hit_in(words: set[str], stems: set[str]) -> str | None:
    for w in words:
        hit = _stem_hit(w, stems)
        if hit:
            return hit
    return None


def key_of(s: str) -> str:
    return s.strip().lower().replace("ё", "е")
